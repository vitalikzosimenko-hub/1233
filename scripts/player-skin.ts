// Turns a Minecraft skin PNG into the game's embedded player skin (src/game/player-skin-data.ts).
// The skin is a 64x64 sheet with classic (4-pixel) arms; a whole-number upscale of one (such as a
// 1024x1024 export) is read back at 64x64 from the middle of each block. Run:
//   node_modules/.bin/tsx scripts/player-skin.ts <skin.png> [name]
import { writeFileSync } from 'node:fs';
import path from 'node:path';
import sharp from 'sharp';

const ROOT = path.resolve(path.dirname(new URL(import.meta.url).pathname), '..');
const OUT = path.join(ROOT, 'src/game/player-skin-data.ts');

const file = process.argv[2];
if (!file) {
  console.error('usage: tsx scripts/player-skin.ts <skin.png> [name]');
  process.exit(1);
}
const name = process.argv[3] ?? path.basename(file);

const { data, info } = await sharp(file).ensureAlpha().raw().toBuffer({ resolveWithObject: true });
if (info.width !== info.height || info.width % 64 !== 0) {
  console.error(`${file}: ${info.width}x${info.height} is not a 64x64 skin (or a whole multiple of one)`);
  process.exit(1);
}
const k = info.width / 64;
const rgba = Buffer.alloc(64 * 64 * 4);
let blocky = true;
for (let y = 0; y < 64; y += 1) {
  for (let x = 0; x < 64; x += 1) {
    const at = (((y * k + (k >> 1)) * info.width) + x * k + (k >> 1)) * 4;
    data.copy(rgba, (y * 64 + x) * 4, at, at + 4);
    // (An upscale repeats each pixel over its block: anything else was resampled and loses detail.)
    const corner = (y * k * info.width + x * k) * 4;
    if (data.readUInt32BE(corner) !== data.readUInt32BE(at)) blocky = false;
  }
}
if (!blocky) console.warn(`${file}: not a clean ${k}x upscale; sampled the middle of each block`);

writeFileSync(OUT, `// Generated by scripts/player-skin.ts from ${name}: run it again to change the skin.

/** The player's skin: a 64x64 Minecraft sheet (classic arms, both layers), RGBA rows top down, base64. */
export const PLAYER_SKIN_RGBA =
  '${rgba.toString('base64')}';
`);
console.log(`${OUT}: ${name} (${info.width}x${info.height}, ${k}x)`);
